import { describe, expect, it } from 'vitest';
import { coins, isHomeworkPassed, streakDays } from '../../src/modules/analytics/gamification';

describe('streakDays', () => {
  it('без действий серии нет', () => {
    expect(streakDays([], '2026-09-22')).toBe(0);
  });

  it('действие сегодня — серия 1 день', () => {
    expect(streakDays(['2026-09-22'], '2026-09-22')).toBe(1);
  });

  it('действия каждый день подряд', () => {
    expect(streakDays(['2026-09-20', '2026-09-21', '2026-09-22'], '2026-09-22')).toBe(3);
  });

  it('один пустой день между действиями серию не рвёт и входит в неё', () => {
    // пн, ср, пт — действие раз в 2 дня: серия пн..пт = 5 дней
    expect(streakDays(['2026-09-14', '2026-09-16', '2026-09-18'], '2026-09-18')).toBe(5);
  });

  it('два пустых дня подряд рвут серию — считается только новая', () => {
    expect(streakDays(['2026-09-10', '2026-09-11', '2026-09-14', '2026-09-15'], '2026-09-15')).toBe(
      2,
    );
  });

  it('вчера или позавчера было действие — серия жива, сегодня ещё можно успеть', () => {
    expect(streakDays(['2026-09-19', '2026-09-20'], '2026-09-21')).toBe(2);
    expect(streakDays(['2026-09-19', '2026-09-20'], '2026-09-22')).toBe(2);
  });

  it('с последнего действия прошло три дня — серия сгорела', () => {
    expect(streakDays(['2026-09-19', '2026-09-20'], '2026-09-23')).toBe(0);
  });

  it('повторы и будущие даты не влияют', () => {
    expect(streakDays(['2026-09-22', '2026-09-22', '2026-09-21', '2026-09-30'], '2026-09-22')).toBe(
      2,
    );
  });
});

describe('coins', () => {
  it('50 за посещение и 20 за задание больше 75%', () => {
    expect(
      coins(3, [
        { score: 80, maxScore: 100 },
        { score: 10, maxScore: 10 },
        { score: 75, maxScore: 100 },
        { score: null, maxScore: 100 },
      ]),
    ).toBe(3 * 50 + 2 * 20);
  });

  it('ровно 75% не засчитывается, 76% — засчитывается', () => {
    expect(isHomeworkPassed(75, 100)).toBe(false);
    expect(isHomeworkPassed(76, 100)).toBe(true);
    expect(isHomeworkPassed(null, 100)).toBe(false);
  });

  it('без активности — 0', () => {
    expect(coins(0, [])).toBe(0);
  });
});
